let currentLang = localStorage.getItem('freelancehub_lang') || 'en';

function setLanguage(lang) {
  if (translations[lang]) {
    currentLang = lang;
    localStorage.setItem('freelancehub_lang', lang);
    applyTranslations();
    
    // Dispatch custom event for active page re-rendering if needed
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
  }
}

function getTranslation(key) {
  if (!key) return '';
  const langObj = translations[currentLang] || translations['en'];
  return langObj[key] || translations['en'][key] || key;
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const text = getTranslation(key);
    if (el.tagName === 'INPUT' && el.getAttribute('placeholder')) {
      el.setAttribute('placeholder', text);
    } else {
      el.innerText = text;
    }
  });

  // Update language selector dropdown if present
  const langSelects = document.querySelectorAll('.lang-selector-select');
  langSelects.forEach(sel => {
    sel.value = currentLang;
  });
}

document.addEventListener('DOMContentLoaded', () => {
  applyTranslations();
});
